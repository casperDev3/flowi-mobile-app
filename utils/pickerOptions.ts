/**
 * utils/pickerOptions.ts — що показує список вибору і коли в ньому зʼявляється
 * рядок «створити».
 *
 * Логіка витягнута з компонента саме тому, що вона не про вигляд. Головне
 * правило: набране в пошуку САМЕ ПО СОБІ записом не стає. Раніше категорію на
 * вебі можна було ввести вільним текстом — і кожна одруківка ставала новою
 * категорією, під якою назавжди лишалась одна операція. Тепер набране лише
 * фільтрує список, а новий запис зʼявляється тільки явним натиском «+».
 */

/** Мінімум, потрібний для пошуку: підпис, який людина бачить у рядку. */
export interface PickerLike {
  label: string;
}

/** Рядки, у підписі яких трапляється запит. Порожній запит — увесь список. */
export function filterPickerOptions<T extends PickerLike>(options: T[], query: string): T[] {
  const q = query.trim().toLowerCase();
  if (!q) return options;
  return options.filter(option => option.label.toLowerCase().includes(q));
}

/**
 * Назва для нового запису або null, якщо створювати нічого.
 *
 * null повертається у двох випадках: порожній запит (назви немає) і точний збіг
 * із наявним рядком. Другий випадок важливіший: інакше «+» поруч із уже
 * знайденою категорією створював би її дубль, а після синхронізації два записи
 * з тим самим похідним id злилися б в один — і людина не зрозуміла б, куди
 * поділась «щойно додана» категорія. Порівняння без урахування регістру:
 * «Їжа» і «їжа» — та сама категорія для ока, і має бути тією самою для нас.
 */
export function pickerCreateName(options: PickerLike[], query: string): string | null {
  const name = query.trim();
  if (!name) return null;
  const lower = name.toLowerCase();
  return options.some(option => option.label.trim().toLowerCase() === lower) ? null : name;
}
