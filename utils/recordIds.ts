/**
 * utils/recordIds.ts — правила id для записів, що синхронізуються.
 *
 * Жили в store/migrations.ts, але потрібні ще й формам. Причина конкретна:
 * categoryMapToRows МОВЧКИ відкидає рядок із задовгим id, тож без перевірки
 * у формі людина бачить «додано», а категорія зникає при наступному читанні —
 * виглядає як втрата даних, хоч нею не є.
 *
 * Файл навмисно без жодної залежності від сховища: інакше його не можна було б
 * імпортувати з чистої логіки в utils/ — store/storage тягне AsyncStorage,
 * якого в тестовому середовищі немає.
 */

/**
 * Межа довжини id. Її задає ключ запису в протоколі синхронізації, тому
 * порушення виявляється не при збереженні, а вже після обміну.
 */
export const MAX_RECORD_ID_LENGTH = 64;

/** Порожній рядок як id зламав би syncRecordKey — такі записи пропускаємо. */
export function isUsableId(value: unknown): value is string {
  return typeof value === 'string'
    && value.length > 0
    && value.length <= MAX_RECORD_ID_LENGTH;
}

/**
 * id категорії ПОХІДНИЙ від типу й назви навмисно: дві однакові категорії,
 * заведені офлайн на двох пристроях, мусять злитися в один запис, а не
 * подвоїтись під випадковими id.
 */
export function categoryRowId(type: string, name: string): string {
  return `${type}:${name}`;
}
