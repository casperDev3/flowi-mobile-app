/**
 * components/time/dials/shared.ts — спільний контракт циферблатів.
 *
 * Кожен циферблат сам підписується на тікер (useClockTick) і сам рахує час від
 * startedAt. Передавати йому готові секунди пропом було б помилкою: тоді
 * щосекунди перемальовувався б батько, тобто вся сітка з чотирьох клітинок і
 * підзавданнями, замість одного вузла всередині клітинки.
 *
 * Глибина приходить сюди ГОТОВОЮ: матеріал рахує диспетчер TimerDial один раз
 * на циферблат, а не кожен варіант для себе. Це не економія рядків — це єдине,
 * що тримає десять циферблатів в одній сцені: одне джерело світла, одна пара
 * тем, одна канавка. Тому в пропах є isDark (тема) і немає жодного літерала
 * rgba(0,0,0,…) у самих циферблатах.
 */
import { useId } from 'react';
import type { TextStyle } from 'react-native';

import type { DialMaterial } from '@/utils/dialMaterial';

export interface DialColors {
  text: string;
  sub: string;
  border: string;
  accent: string;
}

export interface DialProps {
  /** ISO-мітка старту сесії — єдине джерело часу. */
  startedAt: string;
  /**
   * Полотно циферблата: коротша сторона доступного місця. Кожен варіант сам
   * вирішує, як його витратити — колу потрібен квадрат, лінійці ширина.
   */
  size: number;
  colors: DialColors;
  /**
   * Тема. Скло у світлій темі — не те саме, що в темній: там воно м'яка тінь
   * чорнилом, тут підсвічений край. Без цього прапора матеріал довелося б
   * зашивати літералами в кожному циферблаті.
   */
  isDark?: boolean;
  /**
   * Плавний хід замість тіку раз на секунду. Ставить ЛИШЕ той, хто малює
   * циферблат на весь екран (див. utils/dialSmooth): у сітці й в аркуші вибору
   * це були б 60 Гц × кількість на екрані при ввімкненому дисплеї.
   */
  smooth?: boolean;
}

/** Те, що доходить до самої реалізації: матеріал уже порахований. */
export interface DialRenderProps extends DialProps {
  material: DialMaterial;
}

/** Табличні цифри — інакше ширина розрядів гуляє і рядок сіпається щосекунди. */
export const TABULAR: TextStyle = { fontVariant: ['tabular-nums'] };

export const pad = (n: number): string => String(n).padStart(2, '0');

/** Частки поточної хвилини / години / півдоби — для дуг, стрілок і орбіт. */
export function cycles(seconds: number) {
  return {
    second: (seconds % 60) / 60,
    minute: (seconds % 3600) / 3600,
    hour: (seconds % 43200) / 43200,
  };
}

/** Полотно всіх радіальних — 100×100, щоб геометрію можна було читати як відсотки. */
export const BOX = 100;
export const circumference = (r: number) => 2 * Math.PI * r;

/**
 * Унікальний суфікс для ідентифікаторів <Defs> цього екземпляра.
 *
 * На екрані одночасно живе до десяти <Svg> (аркуш вибору показує всі
 * циферблати разом), а посилання url(#id) шукає ПЕРШИЙ такий id у документі.
 * Без суфікса всі циферблати взяли б градієнт того, хто змонтувався раніше.
 *
 * useId() із чисткою, а не власний лічильник. React 19 справді повертає
 * ідентифікатори із символами, недопустимими в XML-імені, — але прибрати їх
 * дешевше, ніж тримати модульний лічильник: той доводилось інкрементувати
 * ВСЕРЕДИНІ ініціалізатора useState, а ініціалізатор мусить бути чистим. У
 * StrictMode й на відкинутих конкурентних рендерах він викликається зайві
 * рази і просто з'їдає ідентифікатори.
 */
export function useDialUid(): string {
  return `d${useId().replace(/[^a-zA-Z0-9_-]/g, '')}`;
}
