/**
 * utils/dialSmooth.ts — КОМУ дістається плавний хід і ЗВІДКИ береться фаза.
 *
 * Плавність тут не оздоблення, а стаття витрат. Повноекранний режим тримає
 * дисплей увімкненим (useKeepAwake) годинами, тож 60 Гц у кожній клітинці —
 * це 60 Гц × кількість таймерів на весь час роботи.
 *
 * Тому вирішує РОЗМІР, а не кількість. Домовлено було «рух там, де його
 * видно», і саме розмір відповідає на це питання: на iPad із двома таймерами
 * кожен циферблат більший за 500pt — плавність там читається, і відмовляти їй
 * лише через те, що таймерів двоє, немає підстав. Навпаки, коли їх стає багато,
 * розкладка сама зменшує полотно нижче порога, і плавність вимикається без
 * окремого правила про кількість.
 *
 * Стеля все одно потрібна: у сітці 2×2 це до чотирьох анімацій одночасно. Вони
 * дешеві саме тому, що йдуть shared value reanimated і не викликають рендер
 * React, — але безмежно їх плодити не можна, і поріг розміру це й обмежує.
 *
 * Дрібні при цьому НЕ починають перемальовуватись частіше: спільний тікер
 * (hooks/use-clock-tick) лишається одним на застосунок і далі б'є раз на
 * секунду. Плавність живе окремим шляхом — shared value reanimated, який не
 * викликає рендер React узагалі.
 */

/**
 * Нижче цього полотна суб-секундний рух не читається: стрілка проходить
 * менше пункту за кадр, і плавність відрізняється від тіку лише витратою
 * батареї.
 */
export const SMOOTH_MIN_DIAL = 200;

export interface SmoothDialOptions {
  /** Полотно, яке дала розкладка. Єдине, що вирішує. */
  dialSize: number;
  /** Reduce Motion у системі. */
  reduced: boolean;
}

export function shouldSmoothDial(o: SmoothDialOptions): boolean {
  if (o.reduced) return false;
  return o.dialSize >= SMOOTH_MIN_DIAL;
}

export interface PhaseAnchor {
  /** Яку частку поточної секунди вже пройдено на момент прив'язки. */
  from: number;
  /** Скільки мілісекунд лишилось до наступної секунди. */
  duration: number;
}

/**
 * Прив'язка плавної фази до справжнього годинника.
 *
 * Фаза не крутиться сама по собі циклом «1000 мс по колу»: за годину такий
 * цикл розходиться з числом під циферблатом на видиму частку секунди, і
 * стрілка починає обганяти власні цифри. Замість цього фаза заново
 * прив'язується на КОЖНОМУ тіку — тобто раз на секунду похибка обнуляється.
 *
 * Повертає, з якого місця стартувати й скільки лишилось до кінця секунди.
 */
export function smoothPhaseAnchor(startedAt: string, now: number): PhaseAnchor {
  const started = Date.parse(startedAt);
  const elapsed = Number.isNaN(started) ? 0 : Math.max(0, now - started);
  const withinSecond = elapsed % 1000;
  return { from: withinSecond / 1000, duration: 1000 - withinSecond };
}
