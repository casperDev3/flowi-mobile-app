/**
 * utils/projectColors.ts — палітра проєктів і вибір кольору для нового проєкту.
 *
 * Палітра лежить тут, а не в екрані app/projects.tsx, з двох причин. По-перше,
 * її тепер читає чиста логіка, а імпорт екрана тягне AsyncStorage і все дерево
 * компонентів. По-друге, той самий масив, у тому самому порядку, живе на вебі
 * (lib/project-colors.ts) — палітри мусять лишатися однією річчю, інакше один
 * і той самий проєкт матиме різний колір залежно від пристрою.
 *
 * Колір проєкту — не прикраса: це крапка біля задачі, бейдж і колір на
 * графіках. Тому проєкт, створений швидко з пікера, НЕ може щоразу отримувати
 * перший колір палітри — інакше всі такі проєкти зіллються в одну масу і колір
 * перестане розрізняти.
 */

/** Порядок масиву — частина правила: за ним іде пошук вільного кольору. */
export const PROJECT_COLORS: readonly string[] = [
  '#7C3AED', '#0EA5E9', '#10B981', '#F59E0B',
  '#EF4444', '#8B5CF6', '#EC4899', '#6366F1',
];

/** Мінімум, потрібний для лічильника: сам колір. */
export interface ProjectColorLike {
  color?: string | null;
}

/**
 * Ключ для порівняння кольорів.
 *
 * Регістр шістнадцяткового запису значення не має: '#7c3aed' і '#7C3AED' — той
 * самий колір. Порівнюємо в нижньому регістрі, щоб проєкт, збережений колись
 * іншим клієнтом, не «звільняв» колір, який насправді зайнятий.
 */
function colorKey(value: string | null | undefined): string {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

/**
 * Колір для нового проєкту: перший НЕВЖИВАНИЙ у палітрі, а коли зайняті всі —
 * той, що вживається найрідше.
 *
 * Три рішення, які МУСЯТЬ збігатися з веб-копією, інакше два клієнти дадуть
 * тому самому проєкту різний колір:
 *
 * 1. Рахуються УСІ проєкти, разом з архівними. Архівний проєкт не зник — його
 *    повертають з архіву, і поверненню не можна віддавати колір, який тим
 *    часом уже зайняв хтось інший.
 * 2. Нічия розвʼязується ПЕРШИМ індексом палітри, а не порядком проєктів у
 *    даних: порядок на телефоні (AsyncStorage після синку) і на вебі (масив
 *    data-context) різний, тож спиратися на нього не можна.
 * 3. Кольори поза палітрою (проєкти, пофарбовані руками до цієї функції)
 *    лічильник ігнорує, а не ламається на них.
 *
 * Порожня палітра повертає порожній рядок: вигадувати колір, якого власник
 * палітри не давав, гірше, ніж віддати помітно порожнє значення.
 */
export function nextProjectColor(
  projects: readonly ProjectColorLike[],
  palette: readonly string[] = PROJECT_COLORS,
): string {
  if (palette.length === 0) return '';

  // Дубль у палітрі рахуємо за першим входженням — інакше той самий колір мав
  // би два незалежні лічильники й виглядав би вільним.
  const indexByColor = new Map<string, number>();
  palette.forEach((color, index) => {
    const key = colorKey(color);
    if (!indexByColor.has(key)) indexByColor.set(key, index);
  });

  const counts = palette.map(() => 0);
  for (const project of projects) {
    const index = indexByColor.get(colorKey(project?.color));
    if (index === undefined) continue;
    counts[index] += 1;
  }

  let best = 0;
  for (let index = 1; index < counts.length; index += 1) {
    // Строго менше: за рівних лічильників лишається менший індекс палітри.
    if (counts[index] < counts[best]) best = index;
  }
  return palette[best];
}
