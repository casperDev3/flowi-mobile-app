import { Platform } from 'react-native';

/**
 * Медичні розділи «Профілактики» — ліки, медогляди, щеплення й звіт для лікаря.
 *
 * Google Play дозволяє «медичні» застосунки (категорії «Ліки й контроль
 * лікування», «Профілактика захворювань») лише акаунтам організацій; Flowi
 * публікується з особистого акаунта, тож на Android ці розділи сховано, а
 * декларація «Застосунки для здоров'я» в Play Console вказує тільки фітнес,
 * харчування й сон. Звички лишаються — це не медична функція.
 * iOS і веб не обмежені. Повернути — коли з'явиться акаунт організації.
 */
export function medicalFeaturesEnabled(os: string = Platform.OS): boolean {
  return os !== 'android';
}
